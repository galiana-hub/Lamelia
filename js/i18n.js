let current = 'en';

export function detectLang() {
  const nav = typeof navigator !== 'undefined' ? navigator : null;
  const first = (nav && ((nav.languages && nav.languages[0]) || nav.language)) || 'en';
  const code = String(first).slice(0, 2).toLowerCase();
  return LANGS[code] ? code : 'en';
}

export function setLang(lang) {
  current = LANGS[lang] ? lang : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = current;
  return current;
}

export function getLang() {
  return current;
}

export function t(key, vars) {
  let s = (DICT[current] && DICT[current][key]) ?? DICT.en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}
